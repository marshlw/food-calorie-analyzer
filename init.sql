
-- создаём отдельного пользователя приложения
DO $$
BEGIN
   IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'fooduser') THEN
      CREATE ROLE fooduser WITH LOGIN PASSWORD 'foodpass';
   END IF;
END
$$;

-- даём права
GRANT ALL PRIVILEGES ON DATABASE fooddb TO fooduser;

-- подключаемся к базе
\c fooddb;

-- права на схему
GRANT ALL ON SCHEMA public TO fooduser;

-- чтобы новые таблицы тоже были доступны
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT ALL ON TABLES TO fooduser;

