// Капитализация названий продуктов/блюд/ингредиентов для отображения.
// В БД имена продуктов хранятся в нижнем регистре (нужно для точного
// сопоставления ингредиентов с базой КБЖУ в ml_service.get_product) —
// капитализация делается только на уровне UI, значения не меняются.
export const capitalize = (s: string | null | undefined): string =>
  s ? s.charAt(0).toUpperCase() + s.slice(1) : s ?? ''
