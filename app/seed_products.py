def seed_products(session) -> int:
    """Идемпотентно добавляет недостающие продукты. Возвращает число вставленных."""
    existing = {row[0] for row in session.query(models.Product.name).all()}
    inserted = 0
    for name, (cal, protein, fat, carbs) in PRODUCTS.items():
        if name in existing:
            continue
        session.add(models.Product(name=name, calories=cal, protein=protein, fat=fat, carbs=carbs))
        inserted += 1
    if inserted:
        session.commit()
    logger.info("Product seed complete", extra={"inserted": inserted, "total": len(PRODUCTS)})
    return inserted
