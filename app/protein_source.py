def classify(name: Optional[str]) -> str:
    """Возвращает источник белка продукта: animal | plant | mixed.

    Неизвестные/неоднозначные продукты считаем смешанными (mixed): это
    консервативно делит белок поровну, а не приписывает его к одному источнику.
    """
    key = (name or "").strip().lower()
    if not key:
        return MIXED
    for needle, ptype in RULES:
        if needle in key:
            return ptype
    return MIXED


def split_protein(protein_g: float, ptype: Optional[str]) -> Tuple[float, float]:
    """Делит белок (г) на (животный, растительный) по тегу источника.

    mixed → делим по MIXED_ANIMAL_SHARE; неизвестный тег → как mixed.
    """
    p = float(protein_g or 0)
    t = (ptype or MIXED).lower()
    if t == ANIMAL:
        return (round(p, 1), 0.0)
    if t == PLANT:
        return (0.0, round(p, 1))
    animal = round(p * MIXED_ANIMAL_SHARE, 1)
    return (animal, round(p - animal, 1))


def backfill(session) -> int:
    """Проставляет protein_type существующим продуктам без тега.
    Возвращает число обновлённых строк. Идемпотентно."""
    from . import models

    updated = 0
    rows = (
        session.query(models.Product)
        .filter((models.Product.protein_type.is_(None)) | (models.Product.protein_type == ""))
        .all()
    )
    for product in rows:
        product.protein_type = classify(product.name)
        updated += 1
    if updated:
        session.commit()
    return updated
